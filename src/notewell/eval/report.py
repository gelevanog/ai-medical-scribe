"""results/summary.json (read by the UI's evaluation page) and results/report.md from the committed artifacts."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from notewell.config import Settings


def _load(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def _pct(x: float | None) -> str:
    return "n/a" if x is None else f"{100 * x:.1f}%"


def build_report(settings: Settings) -> Path:
    r = settings.results_dir
    runs: dict[str, Any] = {}
    for run_file in sorted((r / "runs").glob("*/summary.json")):
        run_data = _load(run_file)
        runs[run_file.parent.name] = {k: v for k, v in run_data.items() if k not in {"phi_leak_details"}}
    asr: dict[str, Any] = {}
    for asr_file in sorted((r / "asr").glob("*.json")):
        asr_data = _load(asr_file)
        asr[asr_file.stem] = {k: v for k, v in asr_data.items() if k != "cases"}
    summary = {
        "runs": runs,
        "asr": asr,
        "phi": _load(r / "phi" / "summary.json"),
        "phi_challenge_frozen": {
            "v1_on_set1": _brief(_load(r / "phi" / "challenge_v1_frozen.json")),
            "v2_on_set2": _brief(_load(r / "phi" / "challenge2_v2_frozen.json")),
        },
        "canary": {k: v for k, v in (_load(r / "canary" / "canary.json") or {}).items() if k != "cases"},
        "guards": _load(r / "guards.json"),
        "calls": _load(r / "calls_summary.json"),
        "smoke": _load(r / "smoke.json"),
    }
    (r / "summary.json").write_text(json.dumps(summary, indent=1), encoding="utf-8")
    lines = [
        "# Notewell evaluation report",
        "",
        "Generated by `notewell eval report` from the artifacts in this directory.",
        "",
    ]
    for name, run in runs.items():
        lines += [
            f"## Notes run `{name}`: {run.get('model')} on {run.get('transcripts')} transcripts",
            "",
            "| Metric | Value |",
            "|---|---|",
            f"| Visits / gold facts / statements | {run.get('visits')} / {run.get('gold_facts')} / {run.get('statements')} |",
            f"| Fact recall (any section / correct section) | {_pct(run.get('fact_recall'))} / {_pct(run.get('fact_recall_section_correct'))} |",
            f"| Statements matching a gold fact | {_pct(run.get('gold_matched_precision'))} |",
            f"| Unsupported statements (grounding guard) | {_pct(run.get('unsupported_rate'))} (partial: {_pct(run.get('partial_rate'))}) |",
            f"| Negation errors / pertinent negatives in gold | {run.get('negation_errors')} / {run.get('negatives_in_gold')} |",
            f"| Trap errors | {run.get('trap_errors')} |",
            f"| Medication recall / correct dose | {_pct(run.get('medication_recall'))} / {_pct(run.get('medication_dose_correct'))} |",
            f"| ICD-10-CM primary top-1 / top-3 / top-3 lenient / top-3 category | {_pct(run.get('icd_top1'))} / {_pct(run.get('icd_top3'))} / {_pct(run.get('icd_top3_lenient'))} / {_pct(run.get('icd_top3_category'))} |",
            f"| E/M exact / within one level / rule estimate exact | {_pct(run.get('em_exact'))} / {_pct(run.get('em_within_one'))} / {_pct(run.get('em_rule_estimate_exact'))} |",
            f"| PHI leaks in {run.get('payloads_checked')} payloads | {run.get('phi_leaks')} |",
            f"| Failures | {len(run.get('failures') or [])} |",
            "",
        ]
    for name, a in asr.items():
        lines.append(
            f"- ASR `{name}`: WER {_pct(a.get('wer'))}, key terms {_pct(a.get('key_term_recall'))}, roles {_pct(a.get('role_accuracy'))}, RTF {a.get('real_time_factor_p50')}"
        )
    path = r / "report.md"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def _brief(data: Any) -> Any:
    if not data:
        return None
    return {
        k: data[k]
        for k in ("items", "gold_values", "covered", "recall", "by_type", "negative_items", "negative_items_untouched")
        if k in data
    }
