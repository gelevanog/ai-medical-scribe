"""Runtime settings from environment variables with the NOTEWELL_ prefix (and an optional .env file).

See .env.example for every variable. The defaults run fully offline: the fake LLM provider, the fake (gold-transcript)
speech recognizer and the local mock FHIR server.
"""

from __future__ import annotations

from functools import lru_cache
from pathlib import Path
from typing import Annotated, Literal

from pydantic import Field, field_validator
from pydantic_settings import BaseSettings, NoDecode, SettingsConfigDict

LLMProviderKind = Literal["fake", "openrouter", "openai_compatible"]
STTProviderKind = Literal["fake", "whisper"]

# Chosen by the smoke test before the evaluation run (results/smoke.json).
DEFAULT_FREE_MODEL = "nvidia/nemotron-3-super-120b-a12b:free"
DEFAULT_FREE_FALLBACKS: list[str] = []
DEFAULT_MODELS: dict[str, str] = {"fake": "fake-scribe", "openrouter": DEFAULT_FREE_MODEL, "openai_compatible": ""}

ROOT = Path(__file__).resolve().parents[2]


def _split(value: object) -> object:
    if isinstance(value, str):
        return [item.strip() for item in value.split(",") if item.strip()]
    return value


class Settings(BaseSettings):
    model_config = SettingsConfigDict(env_file=".env", env_prefix="NOTEWELL_", extra="ignore")

    # ---- storage
    data_dir: Path = Path("var")
    """Visit database, encrypted uploads, the local data key. Never committed."""
    dataset_dir: Path = ROOT / "data" / "visits"
    audio_dir: Path = ROOT / "data" / "audio"
    """Synthesized audio of the synthetic visits (generated by `notewell data synth-audio`)."""
    codes_dir: Path = ROOT / "data" / "codes"
    results_dir: Path = ROOT / "results"
    data_key: str = ""
    """Base64 AES-256 key for encryption at rest. Empty = a key file is generated in data_dir (demo only)."""
    retention_days: int = 30
    """`notewell purge` deletes audio and transcripts of signed visits older than this."""
    seed_demo: bool = True
    """Load the synthetic visits into the visit list on first start."""

    # ---- access control (demo-grade; see README > HIPAA-minded design)
    auth_tokens: Annotated[list[str], NoDecode] = Field(default_factory=list)
    """`role:user:token` triples. Empty = demo mode: every request acts as the demo clinician."""
    demo_user: str = "Dr. Demo (clinician)"

    # ---- speech
    stt_provider: STTProviderKind = "fake"
    stt_model: str = "small.en"
    stt_threads: int = 4
    stt_medical_prompt: bool = True
    """Prime Whisper with a short list of drug and clinical terms (initial_prompt)."""
    models_dir: Path = Path.home() / ".cache" / "notewell" / "models"

    # ---- LLM
    llm_provider: LLMProviderKind = "fake"
    llm_model: str = ""
    llm_fallback_models: Annotated[list[str], NoDecode] = Field(default_factory=list)
    llm_base_url: str = ""
    llm_api_key: str | None = None
    openrouter_api_key: str | None = Field(default=None, validation_alias="OPENROUTER_API_KEY")
    openrouter_base_url: str = "https://openrouter.ai/api/v1"
    llm_timeout_seconds: float = 180.0
    llm_max_tokens: int = 6000
    llm_temperature: float = 0.0
    llm_reasoning_effort: str = "low"
    require_free_models: bool = True
    """Refuse OpenRouter model ids that do not end in ':free', ':online' variants, plugins and paid served models."""
    allow_paid_models: bool = False
    """Explicit opt-in for the openai_compatible provider (any metered endpoint) and paid OpenRouter models."""
    llm_cache: bool = False
    llm_cache_dir: Path = Path(".cache") / "llm"
    llm_ledger: Path | None = ROOT / "results" / "calls.jsonl"
    llm_max_calls: int = 800
    llm_max_retries: int = 4
    llm_min_seconds_between_requests: float = 3.0

    # ---- scribe
    code_candidates: int = 25
    """ICD-10-CM candidates retrieved from the official code list and offered to the model."""
    block_on_phi: bool = True
    """Fail closed: refuse a cloud call when the egress check finds a known identifier in the outgoing payload."""

    # ---- FHIR
    fhir_base_url: str = "http://127.0.0.1:8000/mock-fhir"
    """Where `export` posts the transaction bundle: the built-in mock (default) or a HAPI FHIR server's /fhir."""
    organization_name: str = "Notewell Demo Clinic"

    # ---- server
    cors_origins: Annotated[list[str], NoDecode] = Field(default_factory=lambda: ["http://localhost:3000"])
    log_level: str = "INFO"
    log_format: Literal["console", "json"] = "console"

    _split_lists = field_validator("auth_tokens", "llm_fallback_models", "cors_origins", mode="before")(_split)

    @property
    def db_path(self) -> Path:
        return self.data_dir / "notewell.db"

    @property
    def effective_model(self) -> str:
        return self.llm_model or DEFAULT_MODELS[self.llm_provider]


@lru_cache
def get_settings() -> Settings:
    return Settings()
